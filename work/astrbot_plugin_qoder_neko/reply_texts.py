_previous: dict[str, str] = {}


def si_reply(template: str, **values: object) -> str:
    """Vary fixed copy and format its original data once for each reply."""
    variants = REPLY_VARIANTS.get(template, (template,))
    if len(variants) > 1:
        alternatives = [text for text in variants if text != _previous.get(template)]
        selected = choice(alternatives)
        _previous[template] = selected
    else:
        selected = variants[0]
    return selected.format_map(values) if values else selected

